/** Days since 0001-01-01, matching PostgreSQL/Python ordinal dates. */
function toOrdinal(date: Date): number {
  const utc = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  // 719163 = ordinal of 1970-01-01.
  return Math.floor(utc / 86_400_000) + 719163;
}

/** The Verse of the Day for a given date, computed the same way as the seed. */
export function dailyVerseFor(date: Date): string {
  const index = toOrdinal(date) % DAILY_VERSE_POOL.length;
  return DAILY_VERSE_POOL[index];
}

/** Local calendar date as YYYY-MM-DD. */
export function isoDate(date: Date): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}
